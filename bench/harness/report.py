#!/usr/bin/env python3
"""Generate a report from a results folder. Reports are generated, never hand-written.

  python3 bench/harness/report.py bench/results/<run> [--out FILE]

Default output: bench/reports/<run>.md (mock runs: <run>/report.md, which git ignores).
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
import sys
from collections import defaultdict
from pathlib import Path

import taskset

SATURATION = 0.9


def pass_at_k(n: int, c: int, k: int) -> float | None:
    """Unbiased pass@k estimator (Chen et al. 2021): 1 - C(n-c, k) / C(n, k)."""
    if n < k:
        return None
    if n - c < k:
        return 1.0
    return 1.0 - math.comb(n - c, k) / math.comb(n, k)


def fmt(x: float | None, digits: int = 2) -> str:
    if x is None:
        return 'n/a'
    if math.isinf(x):
        return 'inf'
    return f'{x:.{digits}f}'


def summarize(rows: list[dict], k: int) -> dict:
    n = len(rows)
    c = sum(r['passed'] for r in rows)
    total = sum(r['tokens']['total'] for r in rows)
    spec = sum(r['tokens']['spec'] for r in rows)
    until = [r['tokens_until_pass'] for r in rows if r['passed']]
    return {
        'n': n,
        'c': c,
        'pass@1': pass_at_k(n, c, 1),
        f'pass@{k}': pass_at_k(n, c, k),
        'tokens_per_success': total / c if c else math.inf,
        'median_tokens_until_pass': statistics.median(until) if until else None,
        'spec_share': spec / total if total else 0.0,
        'mean_attempts_passing': statistics.mean(r['attempts'] for r in rows if r['passed']) if c else None,
    }


def load(run: Path) -> tuple[dict, list[dict]]:
    manifest = json.loads((run / 'manifest.json').read_text())
    rows = [json.loads(line) for line in (run / 'scores.jsonl').read_text().splitlines() if line.strip()]
    return manifest, rows


def build(run: Path) -> str:
    manifest, rows = load(run)
    k = manifest['settings']['k']
    out = [f'# Report: {manifest["run_id"]}', '']
    out.append(f'Generated by `harness/report.py` from `{run.name}/scores.jsonl`. Do not edit by hand.')
    out.append('')
    out.append(f'- date: {manifest["date"]}')
    out.append(f'- commit: `{manifest["git"]["commit"]}`{" (dirty)" if manifest["git"]["dirty"] else ""}')
    out.append(f'- skill file sha256: `{manifest["skill_file"]["sha256"]}`')
    out.append(f'- task set sha256: `{manifest["tasks_sha256"][:16]}`')
    out.append(f'- tokenizer: {manifest["tokenizer"]}')
    out.append(f'- models: {", ".join(m["id"] for m in manifest["models"])}')
    if all(m['provider'] == 'mock' for m in manifest['models']):
        out += ['', '> **Mock run.** These numbers test the harness, not any model or language.']
    for reason, n in sorted(manifest.get('skipped', {}).items()):
        out.append(f'- skipped {n} cells: {reason}')
    for note in manifest.get('notes', []):
        out.append(f'- {note}')

    cells: dict[tuple, list[dict]] = defaultdict(list)
    for r in rows:
        cells[(r['track'], r['task'], r['style'] or '', r['lang'], r['model'], r['mode'])].append(r)

    out += ['', '## All cells', '']
    out.append(
        f'| track | task | style | lang | model | mode | n | c | pass@1 | pass@{k} | tokens/success '
        '| median tokens to pass | spec share |'
    )
    out.append('|' + '---|' * 13)
    for key in sorted(cells):
        s = summarize(cells[key], k)
        out.append(
            '| ' + ' | '.join(key) + f' | {s["n"]} | {s["c"]} | {fmt(s["pass@1"])} | {fmt(s[f"pass@{k}"])} | '
            f'{fmt(s["tokens_per_success"], 0)} | {fmt(s["median_tokens_until_pass"], 0)} | '
            f'{fmt(s["spec_share"])} |'
        )

    # tiers and saturation (generate track)
    tiers: dict[tuple, list[dict]] = defaultdict(list)
    for r in rows:
        if r['track'] == 'generate':
            tiers[(r['lang'], r['model'], r['mode'], r['tier'])].append(r)
    if tiers:
        out += ['', '## Generate track by tier', '']
        out.append(f'| lang | model | mode | tier | n | pass@1 | pass@{k} | tokens/success |')
        out.append('|' + '---|' * 8)
        for key in sorted(tiers):
            s = summarize(tiers[key], k)
            out.append(
                '| ' + ' | '.join(map(str, key)) + f' | {s["n"]} | {fmt(s["pass@1"])} | {fmt(s[f"pass@{k}"])} | '
                f'{fmt(s["tokens_per_success"], 0)} |'
            )
        hard = [(key, summarize(v, k)['pass@1']) for key, v in tiers.items() if key[3] == 3 and key[0] != 'mime']
        best = max((p for _, p in hard if p is not None), default=None)
        if best is not None and best >= SATURATION:
            out += [
                '',
                (
                    f'**SATURATED:** the best baseline scores {fmt(best)} pass@1 on tier 3 (limit {SATURATION}). '
                    'Add harder tier-3 tasks (rule 3).'
                ),
            ]

    # names track: the core bet
    names: dict[tuple, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r['track'] == 'names':
            names[(r['lang'], r['model'], r['mode'])][r['style']].append(r)
    if names:
        out += ['', '## Names track', '']
        out.append('Prediction: mime scores the same on all three styles; Python and TypeScript drop on `misleading`.')
        out.append('')
        out.append('| lang | model | mode | honest | none | misleading | Δ none | Δ misleading |')
        out.append('|' + '---|' * 8)
        for key in sorted(names):
            p = {s: summarize(names[key][s], k)['pass@1'] if names[key][s] else None for s in taskset.STYLES}
            d_none = p['none'] - p['honest'] if None not in (p['none'], p['honest']) else None
            d_mis = p['misleading'] - p['honest'] if None not in (p['misleading'], p['honest']) else None
            out.append(
                '| ' + ' | '.join(key) + f' | {fmt(p["honest"])} | {fmt(p["none"])} | {fmt(p["misleading"])} '
                f'| {fmt(d_none)} | {fmt(d_mis)} |'
            )
    return '\n'.join(out) + '\n'


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('run', type=Path)
    p.add_argument('--out', type=Path)
    args = p.parse_args(argv)
    run = args.run.resolve()
    if args.out:
        dest = args.out
    elif run.name.endswith('-mock') or '-mock-' in run.name:
        dest = run / 'report.md'
    else:
        dest = taskset.REPORTS / f'{run.name}.md'
    dest.write_text(build(run))
    print(f'wrote {dest}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
